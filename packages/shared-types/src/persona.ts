export function buildPersonaInstruction(config?: PersonaConfig | null): string {
  const style = config?.personaStyle ?? 'friendly_pro';
  const objection = config?.objectionHandling ?? 'balanced';

  const forbidden = [
    ...DEFAULT_FORBIDDEN_PHRASES,
    ...(config?.forbiddenPhrases ?? []),
  ]
    .map((p) => p.trim().toLowerCase())
    .filter(Boolean);
  const uniqueForbidden = [...new Set(forbidden)];

  const parts = [
    `[Стиль общения]\n${CORE_PERSONA_RULES}`,
    PERSONA_STYLE_INSTRUCTIONS[style],
    OBJECTION_HANDLING_INSTRUCTIONS[objection],
  ];

  if (uniqueForbidden.length) {
    parts.push(
      `Никогда не используй и не перефразируй эти формулировки: ${uniqueForbidden.map((p) => `«${p}»`).join(', ')}.`,
    );
  }

  return parts.join('\n\n');
}
